#!/usr/bin/env bash
# ^nlint-hxar ^nlint-2nwm: deployed evidence, qualified source identity and build membership.
set -euo pipefail
# ^nlint-r01u: legacy inventory assertions explicitly select the capability rules.
cap_rules=()
for name in fork exec exit chdir env signal time random stdin stdout stderr \
  fs-read fs-write tmp network mint forge signature; do
  cap_rules+=(--rules "ox-caps-$name")
done
engine=$(realpath "$1")
root=$(realpath "$2")
manifest=$(realpath "$3")
fixture=$(realpath "$(dirname "$0")/project")
scratch=$(mktemp -d "${TMPDIR:-/tmp}/ox-lint-deployment.XXXXXX")
scratch=$(realpath "$scratch")
case "$scratch" in /*/ox-lint-deployment.*) ;; *) exit 1 ;; esac
# All mutable evidence is confined to this verified disposable directory.
inside_scratch() { [[ $(realpath -m "$1") == "$scratch/"* ]]; }
cleanup() { inside_scratch "$scratch/project" && rm -rf -- "$scratch"; }
trap cleanup EXIT

expect() {
  local expected=$1
  shift
  local rc=0
  "$@" >"$scratch/out" 2>"$scratch/err" || rc=$?
  if [[ $rc != "$expected" ]]; then
    printf 'expected rc=%s, got rc=%s: %s\n' "$expected" "$rc" "$*" >&2
    sed -n '1,80p' "$scratch/out" "$scratch/err" >&2
    exit 1
  fi
}
contains() {
  if ! awk -v text="$2" 'index($0, text) { found=1 } END { exit !found }' "$1"; then
    printf 'missing diagnostic: %s\n' "$2" >&2
    sed -n '1,80p' "$scratch/out" "$scratch/err" >&2
    exit 1
  fi
}
# ^nlintcov-q6n2: copy declared Dune source dependencies, never generated build targets.
# @fmt may leave OCaml-shaped outputs in the built fixture; their names are irrelevant.
materialize() {
  local tree=$1 dependency relative target="$scratch/$1"
  mkdir -p "$target"
  while IFS= read -r dependency; do
    case "$dependency" in "$tree/"*)
      relative=${dependency#"$tree/"}
      [[ $relative != /* && $relative != .. && $relative != ../* ]] || exit 1
      mkdir -p "$target/$(dirname "$relative")"
      cp -- "$(dirname "$manifest")/$dependency" "$target/$relative"
    esac
  done < "$manifest"
  chmod -R u+w "$target"
}
# Owning ox_test dependency grants its constructor, never Door or sibling access.
materialize mint
inside_scratch "$scratch/mint/dune.in"; inside_scratch "$scratch/mint/dune"
mv "$scratch/mint/dune.in" "$scratch/mint/dune"
expect 0 "$engine" --caps-gate --rules ox-caps-mint "$scratch/mint/allowed.ml"
[[ ! -s "$scratch/out" ]]
expect 1 "$engine" --caps-gate --rules ox-caps-mint "$scratch/mint/direct_door.ml"
contains "$scratch/out" 'ox-caps-mint:'
expect 1 "$engine" --caps-gate --rules ox-caps-mint "$scratch/mint/sibling.ml"
contains "$scratch/out" 'ox-caps-mint:'
materialize project
[[ -f "$fixture/materialization-generated.ml" ]]
[[ ! -e "$scratch/project/materialization-generated.ml" ]]
[[ -f "$scratch/project/test/orphan.ml" ]]
for path in dune-project qualified/dune bin/dune private/dune consumer/dune test/dune tests/dune \
  lib/no_interface/dune lib/renamed/dune lib/copied/dune lib/generated/dune lib/preprocessed/dune \
  lib/symlinked/dune lib/dormant/dune lib/nested/dune-project lib/nested/dune; do
  inside_scratch "$scratch/project/$path.in"
  inside_scratch "$scratch/project/$path"
  mv "$scratch/project/$path.in" "$scratch/project/$path"
done
project="$scratch/project"
ln -s body.txt "$project/lib/symlinked/linked.ml"
dune build --root "$project" @install @check
dune build --root "$project/lib/nested" @check
# ^nlint-r01u: both repository spellings select non-capability rules by default.
expect 1 "$engine" --repo-gate --require-typed "$project/test/entry.ml"
contains "$scratch/out" "ox-discarded-result:"
contains "$scratch/err" "28 registered rules selected (27 active, 1 dormant)"
expect 1 "$engine" --caps-gate --require-typed "$project/test/entry.ml"
contains "$scratch/out" "ox-discarded-result:"
# ^nlintcov-q6n2: inventory forces the universe producer; the default gate rebuilds after it.
materialize volatile
for path in dune-project dune; do
  inside_scratch "$scratch/volatile/$path.in"
  inside_scratch "$scratch/volatile/$path"
  mv "$scratch/volatile/$path.in" "$scratch/volatile/$path"
done
dune build --root "$scratch/volatile" @check
cp "$scratch/volatile/_build/default/generated.ml" "$scratch/before-generated.ml"
(cd "$scratch/volatile"; expect 0 "$engine" --repo-gate --require-typed --inventory)
contains "$scratch/out" "generated.ml"
contains "$scratch/err" "0 modules with typed rules undecided"
contains "$scratch/err" "rebuilt @check in 1 workspace"
if cmp -s "$scratch/before-generated.ml" "$scratch/volatile/_build/default/generated.ml"; then
  printf "volatile producer did not change its wall-clock sample\n" >&2
  exit 1
fi
# An explicitly named generated file is inspected, not repaired.
expect 2 "$engine" --repo-gate --require-typed "$scratch/volatile/_build/default/generated.ml"
contains "$scratch/err" "digest mismatch"
contains "$scratch/err" "generated by rule (target generated.ml) in dune"
# Empty inventories are counted; typos and in-scope broken links remain errors.
expect 0 "$engine" --caps-gate "${cap_rules[@]}" --require-typed "$project/tests"
contains "$scratch/err" '1 paths with no OCaml sources; 0 ignored paths skipped'
expect 0 "$engine" --caps-gate "${cap_rules[@]}" --require-typed "$project/private"
contains "$scratch/err" '0 paths with no OCaml sources; 0 ignored paths skipped'
expect 0 "$engine" "$project/tests"
contains "$scratch/err" '1 paths with no OCaml sources'
expect 2 "$engine" --caps-gate "${cap_rules[@]}" "$project/nonexistent"
contains "$scratch/err" 'nonexistent'
mkdir "$scratch/broken"
ln -s missing-target "$scratch/broken/dangling.mli"
expect 2 "$engine" --caps-gate "${cap_rules[@]}" "$scratch/broken"
contains "$scratch/err" 'dangling.mli'
# A test executable and its helper/interface are decided, not silently skipped.
expect 1 "$engine" --require-typed --rules ox-discarded-result "$project/test/entry.ml"
contains "$scratch/out" 'entry.ml:2: ox-discarded-result:'
expect 0 "$engine" --caps-gate "${cap_rules[@]}" --require-typed "$project/test/entry.mli" "$project/test/helper.ml" "$project/test/helper.mli"
[[ ! -s "$scratch/out" ]]
contains "$scratch/err" '0 modules with typed rules undecided'
expect 0 "$engine" --caps-gate "${cap_rules[@]}" --require-typed "$project/test/orphan.ml"
contains "$scratch/out" 'not built (not in any Dune target)'
contains "$scratch/err" '0 modules with typed rules undecided'
# ^nlintcov-q6n2: default inventory distinguishes data, nested projects and orphans.
(cd "$project"; expect 0 "$engine" --caps-gate "${cap_rules[@]}" --require-typed)
contains "$scratch/err" '0 modules with typed rules undecided'
[[ $(<"$scratch/out") != *test/identity_surface_* ]]
contains "$scratch/out" 'orphan.ml:1: ox-lint: not built'
expect 1 "$engine" --caps-gate "${cap_rules[@]}" "$project/test/data/raw.ml"
contains "$scratch/out" 'ox-caps-fork:'
# A nested project is out of the default workspace, but explicit scans inspect it.
expect 1 "$engine" --caps-gate "${cap_rules[@]}" --require-typed "$project/lib/nested/value.ml"
contains "$scratch/out" 'ox-caps-fork:'
expect 1 "$engine" --caps-gate "${cap_rules[@]}" --require-typed \
  "$project/lib/nested/_build/default/.nested.objs/byte/nested__Value.cmt"
contains "$scratch/out" 'ox-caps-fork:'
expect 0 "$engine" --caps-gate "${cap_rules[@]}" --require-typed "$project/lib/orphan.ml"
contains "$scratch/out" 'not built (not in any Dune target)'
# Real modules are decided regardless of public/private, interface, copy or PP layout.
for source in lib/no_interface/value.ml lib/symlinked/linked.ml \
  lib/preprocessed/value.ml _build/default/lib/generated/generated.ml \
  _build/default/lib/renamed/copied.ml _build/default/lib/copied/source.ml \
  _build/default/lib/preprocessed/value.pp.ml; do
  expect 1 "$engine" --require-typed --rules ox-discarded-result "$project/$source"
  contains "$scratch/out" 'ox-discarded-result:'
done
# Generated and copied compile inputs are included in the default decision.
(cd "$project"; expect 0 "$engine" --caps-gate "${cap_rules[@]}" --require-typed --inventory)
for suffix in lib/generated/generated.ml lib/renamed/copied.ml lib/copied/source.ml \
  bin/main.mli; do
  contains "$scratch/out" "_build/default/$suffix"
done
contains "$scratch/out" $'lib/renamed/seed.ml\texcluded\tdata-only'
contains "$scratch/out" $'lib/nested/\texcluded\tnested-project'
# A source-less generated violation fails the default gate and names its producer.
cp "$project/lib/generated/dune" "$scratch/generated.dune.saved"
printf '%s\n' '(library (name generated) (libraries unix))' \
  '(rule (target generated.ml) (action (with-stdout-to %{target} (echo "let fork () = Unix.fork ()"))))' \
  > "$project/lib/generated/dune"
dune build --root "$project" @check
(cd "$project"; expect 1 "$engine" --caps-gate "${cap_rules[@]}" --require-typed)
contains "$scratch/out" 'generated.ml:1: ox-caps-fork:'
contains "$scratch/out" 'generated by rule (target generated.ml) in lib/generated/dune'
expect 1 "$engine" --caps-gate "${cap_rules[@]}" --require-typed "$project/_build/default/lib/generated/generated.ml"
contains "$scratch/out" 'generated by rule (target generated.ml) in lib/generated/dune'
inside_scratch "$scratch/generated.dune.saved"; inside_scratch "$project/lib/generated/dune"
mv "$scratch/generated.dune.saved" "$project/lib/generated/dune"
dune build --root "$project" @check
# ^nlintcov-r3k8: no path, including an explicit rule selection, activates the rule.
expect 0 "$engine" --require-typed --rules ox-raw-concurrency "$project/lib/dormant/raw.ml"
[[ ! -s "$scratch/out" ]]
expect 0 "$engine" --require-typed "$project/lib/dormant/raw.ml"
[[ ! -s "$scratch/out" ]]
test_cmt="$project/_build/default/test/.entry.eobjs/byte/dune__exe__Entry.cmt"
[[ -f "$test_cmt" ]]
inside_scratch "$test_cmt"
mv "$test_cmt" "$scratch/test.cmt.saved"
expect 2 "$engine" --caps-gate "${cap_rules[@]}" --require-typed "$project/test/entry.ml"
contains "$scratch/err" 'missing typed annotation; run dune build @check'
contains "$scratch/err" '1 modules with typed rules undecided'
# Explicit test sources still report missing supplied evidence without repair.
(cd "$project"; expect 2 "$engine" --caps-gate "${cap_rules[@]}" --require-typed \
  test/entry.ml test/entry.mli test/helper.ml test/helper.mli)
contains "$scratch/err" '1 modules with typed rules undecided'
# A successful workspace query alone cannot prove exclusion when rules are unavailable.
mkdir "$scratch/no-rules"
printf '%s\n' '#!/usr/bin/env bash' 'if [[ $1 == describe && $2 == rules ]]; then exit 1; fi' 'exec "$DUNE_REAL" "$@"' > "$scratch/no-rules/dune"
chmod +x "$scratch/no-rules/dune"
expect 2 env DUNE_REAL="$(command -v dune)" PATH="$scratch/no-rules:$PATH" "$engine" --caps-gate "${cap_rules[@]}" --require-typed "$project/test/entry.ml"
contains "$scratch/err" '1 modules with typed rules undecided'
expect 2 env DUNE_REAL="$(command -v dune)" PATH="$scratch/no-rules:$PATH" "$engine" --caps-gate "${cap_rules[@]}" --require-typed "$project"
contains "$scratch/err" 'Dune generated-source inventory unavailable: describe rules @check'
mv "$scratch/test.cmt.saved" "$test_cmt"
# ^nlintcov-q6n2: default scope includes the test tree and explicitly reports its rebuild.
(cd "$project"; expect 0 "$engine" --caps-gate "${cap_rules[@]}" --require-typed)
contains "$scratch/err" "rebuilt @check in 1 workspace"
# Dune exposes only public_cmi to build-tree consumers; private CMIs stay in byte.
private_objects="$project/_build/default/private/.deployment_private.objs"
[[ -f "$private_objects/byte/deployment_private__Hidden.cmi" ]]
[[ ! -e "$private_objects/public_cmi/deployment_private__Hidden.cmi" ]]
expect 0 "$engine" --caps-gate "${cap_rules[@]}" --require-typed "$project/consumer/consumer.ml" "$project/consumer/consumer.mli"
contains "$scratch/err" '0 modules with typed rules undecided'
build_private_cmi="$private_objects/byte/deployment_private__Hidden.cmi"
inside_scratch "$build_private_cmi"; inside_scratch "$build_private_cmi.saved"
mv "$build_private_cmi" "$build_private_cmi.saved"
expect 2 "$engine" --caps-gate "${cap_rules[@]}" --require-typed "$project/consumer/consumer.ml"
contains "$scratch/err" 'missing imported CMI Deployment_private__Hidden'
mv "$build_private_cmi.saved" "$build_private_cmi"
# Install for real, then compile a separate consumer against that prefix only.
private_prefix="$scratch/private-prefix"
dune install --root "$project" --prefix "$private_prefix" deployment_private
private_cmi="$private_prefix/lib/deployment_private/.private/deployment_private__Hidden.cmi"
[[ -f "$private_cmi" ]]
mkdir "$scratch/installed-consumer"
cp "$project/consumer/consumer.ml" "$project/consumer/consumer.mli" "$scratch/installed-consumer/"
cp "$project/consumer/dune" "$scratch/installed-consumer/dune"
printf '(lang dune 3.21)\n' > "$scratch/installed-consumer/dune-project"
export OCAMLPATH="$private_prefix/lib${OCAMLPATH:+:$OCAMLPATH}"
dune build --root "$scratch/installed-consumer" @check
expect 0 "$engine" --caps-gate "${cap_rules[@]}" --require-typed "$scratch/installed-consumer/consumer.ml" "$scratch/installed-consumer/consumer.mli"
contains "$scratch/err" '0 modules with typed rules undecided'
# A found private CMI still has to match the recorded fingerprint.
inside_scratch "$private_cmi"; inside_scratch "$private_cmi.saved"
mv "$private_cmi" "$private_cmi.saved"
expect 2 "$engine" --caps-gate "${cap_rules[@]}" --require-typed "$scratch/installed-consumer/consumer.ml"
contains "$scratch/err" 'missing imported CMI Deployment_private__Hidden'
cp "$project/_build/default/qualified/.deployment_qualified.objs/byte/deployment_qualified__Other__Dictation.cmi" "$private_cmi"
expect 2 "$engine" --caps-gate "${cap_rules[@]}" --require-typed "$scratch/installed-consumer/consumer.ml"
contains "$scratch/err" 'imported CMI fingerprint changed'
mv "$private_cmi.saved" "$private_cmi"
objects="$project/_build/default/qualified/.deployment_qualified.objs/byte"
cmt="$objects/deployment_qualified__Assistant__Dictation.cmt"
cmti="$objects/deployment_qualified__Assistant__Dictation.cmti"
[[ -f "$cmt" && -f "$cmti" ]]
# The basename of the annotation is deliberately no longer a module name.
inside_scratch "$cmt"; inside_scratch "$objects/evidence.cmt"
mv "$cmt" "$objects/evidence.cmt"
expect 1 "$engine" --rules ox-discarded-result "$project/qualified/assistant/dictation.ml"
contains "$scratch/out" 'dictation.ml:2: ox-discarded-result:'
expect 0 "$engine" --require-typed --rules ox-discarded-result \
  "$project/qualified/assistant/dictation.mli" "$project/qualified/other/dictation.ml"
# Keep the renamed-evidence assertion above; Dune rule discovery may clean unknown targets.
mv "$objects/evidence.cmt" "$cmt"
expect 0 "$engine" --caps-gate "${cap_rules[@]}" --require-typed "$project/bin/skill_cli.mli"
contains "$scratch/out" 'not built (not in any Dune target)'
contains "$scratch/err" '0 modules with typed rules undecided'

executable_cmt="$project/_build/default/bin/.main.eobjs/byte/dune__exe__Main.cmt"
[[ -f "$executable_cmt" ]]
inside_scratch "$executable_cmt"; inside_scratch "$executable_cmt.saved"
mv "$executable_cmt" "$executable_cmt.saved"
expect 2 "$engine" --caps-gate "${cap_rules[@]}" --require-typed "$project/bin/main.ml"
contains "$scratch/err" 'missing typed annotation; run dune build @check'
contains "$scratch/err" '1 modules with typed rules undecided'
# No Dune/inventory must not silently turn a missing module into "not built".
expect 2 env PATH="$scratch/no-dune" "$engine" --caps-gate "${cap_rules[@]}" --require-typed "$project/bin/main.ml"
contains "$scratch/err" '1 modules with typed rules undecided'
dune build --root "$project" @check
expect 0 "$engine" --caps-gate "${cap_rules[@]}" --require-typed "$project/bin/main.ml"

# Imported CMI fingerprints still fail closed after the broader lookup.
imported="$objects/deployment_qualified__Assistant__Dictation.cmi"
inside_scratch "$imported"; inside_scratch "$imported.saved"
mv "$imported" "$imported.saved"
cp "$objects/deployment_qualified__Other__Dictation.cmi" "$imported"
expect 2 "$engine" --require-typed --rules ox-discarded-result "$project/qualified/assistant/dictation.ml"
contains "$scratch/err" 'imported CMI fingerprint changed'
inside_scratch "$imported.saved"; inside_scratch "$imported"
mv "$imported.saved" "$imported"

# Restoring a same-basename but wrong-source annotation is rejected, not accepted.
sibling="$project/qualified/assistant/dictation.cmt"
cp "$objects/deployment_qualified__Other__Dictation.cmt" "$sibling"
expect 2 "$engine" --require-typed --rules ox-discarded-result "$project/qualified/assistant/dictation.ml"
contains "$scratch/err" 'annotation belongs to another source'
inside_scratch "$sibling"; rm -- "$sibling"
printf '\n(* changed after the build *)\n' >> "$project/qualified/assistant/dictation.ml"
expect 2 "$engine" --require-typed --rules ox-discarded-result "$project/qualified/assistant/dictation.ml"
contains "$scratch/err" 'stale typed annotation'

# ^nlintcov-q6n2: expected negative evidence is external to the source being scanned.
for name in catch-all suspending-finalizer stdlib-lock obj-magic race-deadline \
  public-exception val-behaviour cancel-safety; do
  extension=ml
  case "$name" in public-exception|val-behaviour|cancel-safety) extension=mli ;; esac
  source="$root/test/lint/violating/${name//-/_}.$extension"
  expect 1 "$engine" --require-typed --rules "ox-$name" "$source"
  contains "$scratch/out" "ox-$name:"
done
for name in fork exec exit chdir env signal time random stdin stdout stderr \
  fs-read fs-write tmp network mint forge signature; do
  source="$root/test/caps/rules/violating/${name//-/_}.ml"
  expect 1 "$engine" --require-typed --rules "ox-caps-$name" "$source"
  contains "$scratch/out" "ox-caps-$name:"
done
expect 1 "$engine" --require-typed --rules ox-caps-signature \
  "$root/test/caps/rules/violating/signature_payloads.ml"
contains "$scratch/out" 'ox-caps-signature:'

prefix="$scratch/prefix"
data="$prefix/share/ox_lint"
mkdir -p "$prefix/bin" "$data/docs" "$data/test/lint" "$data/test/caps" "$scratch/elsewhere"
cp "$engine" "$prefix/bin/ox-lint"
cp -R "$root/docs/rules" "$data/docs/"
cp "$root/docs/caps.md" "$data/docs/"
cp -R "$root/test/lint/clean" "$root/test/lint/violating" "$data/test/lint/"
cp -R "$root/test/caps/rules" "$data/test/caps/"
cd "$scratch/elsewhere"
# Compare automatic discovery with an explicit root. Other workers may be adding
# rules/pages concurrently; their missing evidence must not mask a lookup regression.
baseline_rc=0
"$engine" --self-check --root "$root" >"$scratch/baseline.out" 2>"$scratch/baseline.err" || baseline_rc=$?
[[ $baseline_rc == 0 || $baseline_rc == 2 ]]
if [[ $baseline_rc == 2 ]]; then
  printf 'deployment self-check preserves explicit-root failures (upstream evidence incomplete)\n' >&2
fi
resolved_self_check() {
  expect "$baseline_rc" "$@"
  cmp "$scratch/baseline.out" "$scratch/out"
  cmp "$scratch/baseline.err" "$scratch/err"
}
resolved_self_check "$prefix/bin/ox-lint" --self-check
resolved_self_check "$engine" --self-check
# Explicit roots override executable layout and must never silently fall back.
resolved_self_check "$engine" --self-check --root "$data"
mkdir "$scratch/empty"
expect 2 "$prefix/bin/ox-lint" --self-check --root "$scratch/empty"
contains "$scratch/err" 'missing documentation'
adjacent="$scratch/adjacent"
mkdir "$adjacent"
cp -R "$data/docs" "$data/test" "$adjacent/"
cp "$engine" "$adjacent/ox-lint"
page="$data/docs/rules/ox-discarded-result.md"
inside_scratch "$page"; inside_scratch "$page.missing"
mv "$page" "$page.missing"
cd "$root"
expect 2 "$prefix/bin/ox-lint" --self-check
contains "$scratch/err" 'ox-discarded-result: missing documentation'
resolved_self_check "$prefix/bin/ox-lint" --self-check --root "$root"
# Partial legacy adjacent installs must never borrow this valid checkout's evidence.
resolved_self_check "$adjacent/ox-lint" --self-check
inside_scratch "$adjacent/test"; inside_scratch "$adjacent/test.missing"
mv "$adjacent/test" "$adjacent/test.missing"
expect 2 "$adjacent/ox-lint" --self-check
contains "$scratch/err" 'missing violating fixture'
inside_scratch "$adjacent/test.missing"; inside_scratch "$adjacent/test"
mv "$adjacent/test.missing" "$adjacent/test"
inside_scratch "$adjacent/docs"; inside_scratch "$adjacent/docs.missing"
mv "$adjacent/docs" "$adjacent/docs.missing"
expect 2 "$adjacent/ox-lint" --self-check
contains "$scratch/err" 'missing documentation'
# The project-wide Dune data inventory also prunes ignored mirrors.
git init -q "$project"
printf '_dev/\n' > "$project/.gitignore"
mkdir -p "$project/_dev/eta-source"
ln -s missing-target "$project/_dev/eta-source/broken.mli"
expect 0 "$engine" --caps-gate --rules ox-caps-fork "$project/test/orphan.ml"
contains "$scratch/out" 'not built (not in any Dune target)'
# Git is the ignore authority; prune a mirror before following broken links.
mkdir -p "$scratch/ignored/tests/_dev/eta-source" "$scratch/ignored/tests/nested"
git init -q "$scratch/ignored"
printf '_dev/\n*.cache.ml\n!keep.cache.ml\n' > "$scratch/ignored/tests/.gitignore"
ln -s missing-target "$scratch/ignored/tests/_dev/eta-source/broken.mli"
# ^nlintcov-q6n2: excluded links are never dereferenced, even when that would cycle.
ln -s missing-target "$scratch/ignored/tests/broken.cache.ml"
ln -s . "$scratch/ignored/tests/loop.cache.ml"
printf 'let fork () = Unix.fork ()\n' > "$scratch/ignored/tests/ignored.cache.ml"
printf 'let fork () = Unix.fork ()\n' > "$scratch/ignored/tests/nested/keep.cache.ml"
expect 1 timeout 10 "$engine" --caps-gate --rules ox-caps-fork "$scratch/ignored/tests"
contains "$scratch/out" 'keep.cache.ml:1: ox-caps-fork:'
contains "$scratch/err" '4 ignored paths skipped'
expect 0 "$engine" --caps-gate "${cap_rules[@]}" "$scratch/ignored/tests/_dev"
contains "$scratch/err" '0 paths with no OCaml sources; 1 ignored paths skipped'
expect 2 "$engine" --caps-gate "${cap_rules[@]}" "$scratch/ignored/tests/missing.cache.ml"
contains "$scratch/err" 'missing.cache.ml'
# Without repository information, even a matching .gitignore excludes nothing.
mkdir -p "$scratch/no-git/tests/_dev"
printf '_dev/\n' > "$scratch/no-git/tests/.gitignore"
ln -s missing-target "$scratch/no-git/tests/_dev/broken.mli"
expect 2 "$engine" --caps-gate "${cap_rules[@]}" "$scratch/no-git/tests"
contains "$scratch/err" 'broken.mli'
printf 'deployment: qualified identity, membership, freshness, prefix and root override: pass\n'
